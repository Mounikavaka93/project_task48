const byId = new Map(titles.map((item) => [item.id, item]));

export const genres = [...new Set(titles.flatMap((item) => item.genres))].sort((a, b) => a.localeCompare(b));

export function getTitle(id) {
  return byId.get(id);
}

export function titlesIn(row) {
  if (row === "new") {
    return titles
      .filter((item) => item.year >= 2025)
      .sort((a, b) => b.year - a.year || b.rating - a.rating);
  }
  return (collections[row] || []).map((id) => byId.get(id)).filter(Boolean);
}

export function titlesByIndustry(industry) {
  return titles
    .filter((item) => item.industry === industry)
    .sort((a, b) => b.rating - a.rating || b.year - a.year);
}

export function getFeatured() {
  return featuredIds.map((id) => byId.get(id)).filter(Boolean);
}

export function getRelated(id, limit = 10) {
  const current = byId.get(id);
  if (!current) return [];
  return titles
    .filter((item) => item.id !== id && (item.industry === current.industry || item.genres.some((genre) => current.genres.includes(genre))))
    .sort((a, b) => {
      const industryRank = Number(b.industry === current.industry) - Number(a.industry === current.industry);
      return industryRank || b.rating - a.rating;
    })
    .slice(0, limit);
}

export function searchCatalog(query) {
  const needle = query.trim().toLowerCase();
  if (!needle) return [];
  return titles.filter((item) => {
    const haystack = [
      item.title,
      item.industry,
      item.type === "series" ? "series show" : "movie film",
      item.logline,
      item.description,
      item.director,
      ...item.languages,
      ...item.genres,
      ...item.cast.flatMap((person) => [person.name, person.role]),
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(needle);
  });
}

export function queryTitles({ type, genre, industry, sort, row } = {}) {
  let list = row && (row === "new" || collections[row]) ? titlesIn(row) : [...titles];
  if (industry) list = list.filter((item) => item.industry === industry);
  if (type === "movie" || type === "series") list = list.filter((item) => item.type === type);
  if (genre) list = list.filter((item) => item.genres.includes(genre));
  if (!sort && row) return list;
  const copy = [...list];
  if (sort === "rating") copy.sort((a, b) => b.rating - a.rating || b.year - a.year);
  else if (sort === "title") copy.sort((a, b) => a.title.localeCompare(b.title));
  else copy.sort((a, b) => b.year - a.year || b.rating - a.rating);
  return copy;
}

export function typeLabel(type) {
  return type === "series" ? "Series" : "Film";
}

export function runtimeLabel(title) {
  if (title.type === "series") {
    const seasons = title.seasons === 1 ? "1 season" : `${title.seasons} seasons`;
    return `${seasons} · ${title.runtime}`;
  }
  return title.runtime;
}

export function matchScore(title) {
  return Math.min(99, Math.round(title.rating * 10 + 6));
}

